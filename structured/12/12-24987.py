mt = {  (0, " "): (" ", -1, 1),

        (1, " "): (" ", 0, 1),
        (1, "0"): ("1", -1, 2),
        (1, "1"): ("0", -1, 3),

        (2, " "): (" ", 0, 1),
        (2, "0"): ("0", -1, 3),
        (2, "1"): ("1", -1, 3),

        (3, " "): (" ", 0, 1),
        (3, "0"): ("0", -1, 4),
        (3, "1"): ("1", -1, 4),

        (4, " "): (" ", 0, 1),
        (4, "0"): ("0", -1, 1),
        (4, "1"): ("1", -1, 1),


}

b =  "0" * 1000 + "1" * 500
r = list("     " + b + " ")

pos = -1
state = 0

while True:
    r[pos], shift, state = mt[(state, r[pos])]

    if shift == 0: break

    pos += shift

print(sum([int(x) for x in r if x != " "]))
